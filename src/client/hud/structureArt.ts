/** Menu colours for the owner accent. */
const MENU_COLOURS = {
  ...PIXEL_PALETTE,
  F: PIXEL_PALETTE.r,
  f: PIXEL_PALETTE.R,
};

const urls = new Map<StructureArtType, string>();

/** The building's art as an inline SVG URL, for `<img src>`. */
export function structureIconUrl(type: StructureArtType): string {
  let url = urls.get(type);
  if (url === undefined) {
    url = `data:image/svg+xml,${encodeURIComponent(pixelArtSvg(STRUCTURE_ART[type], MENU_COLOURS))}`;
    urls.set(type, url);
  }
  return url;
}
