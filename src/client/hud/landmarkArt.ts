/** The landmark's art as a crisp SVG (one path per colour), or null if it has none. */
export function landmarkArt(name: string): TemplateResult | null {
  const rows = LANDMARK_ART[name];
  if (rows === undefined) return null;
  const paths = pixelArtPaths(rows);
  return svg`<svg
    viewBox="0 0 32 32"
    shape-rendering="crispEdges"
    width="100%"
    height="100%"
    aria-hidden="true"
  >
    ${[...paths].map(
      ([ch, d]) =>
        svg`<path
          fill=${LANDMARK_PALETTE[ch]}
          fill-opacity=${ch === "k" ? OUTLINE_OPACITY : 1}
          d=${d}
        />`,
    )}
  </svg>`;
}
