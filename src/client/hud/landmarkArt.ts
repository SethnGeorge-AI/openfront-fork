/** The landmark's art as a crisp SVG (one path per colour), or null if it has none. */
export function landmarkArt(name: string): TemplateResult | null {
  const rows = LANDMARK_ART[name];
  if (rows === undefined) return null;
  // Each horizontal run of one colour becomes a rectangle in that colour's path.
  const paths = new Map<string, string>();
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== ".") {
        paths.set(
          ch,
          `${paths.get(ch) ?? ""}M${x} ${y}h${end - x}v1h-${end - x}z`,
        );
      }
      x = end;
    }
  });
  return svg`<svg
    viewBox="0 0 32 32"
    shape-rendering="crispEdges"
    width="100%"
    height="100%"
    aria-hidden="true"
  >
    ${[...paths].map(
      ([ch, d]) => svg`<path fill=${LANDMARK_PALETTE[ch]} d=${d} />`,
    )}
  </svg>`;
}
